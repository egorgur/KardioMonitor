package ru.kardiomonitor.features.band.api

import java.time.Instant

/**
 * Привязка браслета — для других контекстов: с какого момента браслет носит этот пациент.
 * История браслета раньше этого момента чужая: браслет клиники выдаётся повторно с тем же
 * ключом (ADR-0011).
 */
fun interface BandPairing {
    /** null — браслет не привязан или привязан до того, как приложение стало запоминать момент. */
    fun pairedAt(): Instant?
}
